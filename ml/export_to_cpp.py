"""
Export trained Random Forest to C++ consumable formats.
=====================================================
Produces:
  1. ml/models/gbm_model.json      - JSON tree structure for runtime loading
  2. ml/models/compiled_forest.h   - Compile-time embedded C++ header with
                                     switch-case tree traversal (zero-overhead)

The JSON format is loaded at runtime by DecisionForestModel::LoadFromJSON().
The compiled header is an optional zero-parse-cost alternative.
"""

import joblib
import json
import os
import numpy as np
import pandas as pd


# Feature ordering (must match train_model.py output after pd.get_dummies)
FEATURE_NAMES = [
    "flops",              # 0
    "bytes_in",           # 1
    "bytes_out",          # 2
    "pcie_load",          # 3
    "gpu_queue_depth",    # 4
    "transfer_time_us",   # 5
    "task_type_CONV2D",   # 6  (one-hot)
    "task_type_QUICKSORT",# 7  (one-hot)
    "task_type_SGEMM",    # 8  (one-hot)
    "task_type_SPMV",     # 9  (one-hot)
]


def export_forest_to_json(model_path="ml/models/rf_scheduler.pkl",
                          output_path="ml/models/gbm_model.json"):
    """Export the sklearn RandomForest to a JSON format that the C++ runtime can parse."""
    clf = joblib.load(model_path)
    forest_data = {
        "n_estimators": len(clf.estimators_),
        "n_features": len(FEATURE_NAMES),
        "feature_names": FEATURE_NAMES,
        "trees": [],
    }

    for tree_idx, estimator in enumerate(clf.estimators_):
        tree = estimator.tree_
        tree_data = {
            "n_nodes": tree.node_count,
            "max_depth": int(tree.max_depth),
            "feature": tree.feature.tolist(),
            "threshold": tree.threshold.tolist(),
            "children_left": tree.children_left.tolist(),
            "children_right": tree.children_right.tolist(),
            "value": [],
        }
        for i in range(tree.node_count):
            class_counts = tree.value[i][0].tolist()
            tree_data["value"].append(class_counts)

        forest_data["trees"].append(tree_data)

    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, "w") as f:
        json.dump(forest_data, f, indent=2)

    total_nodes = sum(t["n_nodes"] for t in forest_data["trees"])
    print(f"Exported {len(clf.estimators_)} trees to {output_path}")
    print(f"  Total nodes: {total_nodes}")
    print(f"  Avg depth: {np.mean([t['max_depth'] for t in forest_data['trees']]):.1f}")


def generate_cpp_header(model_path="ml/models/gbm_model.json",
                        header_path="ml/models/compiled_forest.h"):
    """Generate a C++ header with the forest compiled as switch-case statements."""
    with open(model_path) as f:
        forest = json.load(f)

    lines = [
        "// Auto-generated by ml/export_to_cpp.py — DO NOT EDIT",
        "// This header contains a compiled random forest for zero-overhead inference.",
        "//",
        "// Feature vector layout (10 doubles):",
    ]
    for i, name in enumerate(FEATURE_NAMES):
        lines.append(f"//   [{i}] {name}")
    lines += [
        "//",
        "// Returns: 0 = CPU, 1 = GPU",
        "",
        "#ifndef COMPILED_FOREST_H",
        "#define COMPILED_FOREST_H",
        "",
        "#include <array>",
        "",
        "namespace compiled_forest {",
        "",
        f"static constexpr int N_TREES = {forest['n_estimators']};",
        f"static constexpr int N_FEATURES = {len(FEATURE_NAMES)};",
        "",
    ]

    for ti, tree in enumerate(forest["trees"]):
        n = tree["n_nodes"]
        feat = tree["feature"]
        thresh = tree["threshold"]
        left = tree["children_left"]
        right = tree["children_right"]
        vals = tree["value"]

        lines.append(f"inline int predict_tree_{ti}(const double* features) {{")
        lines.append(f"    int node = 0;")
        lines.append(f"    while (true) {{")
        lines.append(f"        switch (node) {{")

        for i in range(n):
            lines.append(f"            case {i}:")
            if left[i] == -1:
                class_0 = vals[i][0]
                class_1 = vals[i][1] if len(vals[i]) > 1 else 0
                pred = 0 if class_0 >= class_1 else 1
                lines.append(f"                return {pred};")
            else:
                lines.append(f"                node = (features[{feat[i]}] <= {thresh[i]}) ? {left[i]} : {right[i]};")
                lines.append(f"                break;")

        lines.append(f"            default: return 0;")
        lines.append(f"        }}")
        lines.append(f"    }}")
        lines.append(f"}}")
        lines.append("")

    # Majority-vote prediction function
    lines.append("// Returns 1 (GPU) if majority of trees vote GPU, else 0 (CPU).")
    lines.append("inline int predict(const double* features) {")
    lines.append("    int votes_gpu = 0;")
    for ti in range(forest["n_estimators"]):
        lines.append(f"    votes_gpu += predict_tree_{ti}(features);")
    lines.append(f"    return (votes_gpu > N_TREES / 2) ? 1 : 0;")
    lines.append("}")
    lines.append("")

    # Probability function (fraction of trees voting GPU)
    lines.append("// Returns the fraction of trees voting for GPU (0.0 to 1.0).")
    lines.append("inline double predict_gpu_probability(const double* features) {")
    lines.append("    int votes_gpu = 0;")
    for ti in range(forest["n_estimators"]):
        lines.append(f"    votes_gpu += predict_tree_{ti}(features);")
    lines.append(f"    return static_cast<double>(votes_gpu) / static_cast<double>(N_TREES);")
    lines.append("}")
    lines.append("")
    lines.append("}  // namespace compiled_forest")
    lines.append("")
    lines.append("#endif  // COMPILED_FOREST_H")

    with open(header_path, "w") as f:
        f.write("\n".join(lines))

    print(f"Generated C++ header at {header_path}")
    print(f"  {forest['n_estimators']} trees, "
          f"{sum(t['n_nodes'] for t in forest['trees'])} total nodes")


def validate_export(model_path="ml/models/rf_scheduler.pkl",
                    json_path="ml/models/gbm_model.json",
                    csv_path="ml/dataset.csv",
                    n_samples=100):
    """Validate that JSON export matches sklearn predictions on random samples."""
    clf = joblib.load(model_path)

    with open(json_path) as f:
        forest_json = json.load(f)

    df = pd.read_csv(csv_path)
    df = pd.get_dummies(df, columns=["task_type"])
    feature_cols = [c for c in df.columns if c not in ["optimal_device", "cpu_time_us", "gpu_time_us"]]
    X = df[feature_cols].values

    # Sample random rows
    np.random.seed(0)
    indices = np.random.choice(len(X), min(n_samples, len(X)), replace=False)

    mismatches = 0
    for idx in indices:
        features = X[idx]
        sklearn_pred = clf.predict(features.reshape(1, -1))[0]

        # Simulate JSON forest prediction
        gpu_votes = 0
        for tree_data in forest_json["trees"]:
            node = 0
            while tree_data["children_left"][node] != -1:
                feat_idx = tree_data["feature"][node]
                if features[feat_idx] <= tree_data["threshold"][node]:
                    node = tree_data["children_left"][node]
                else:
                    node = tree_data["children_right"][node]
            class_counts = tree_data["value"][node]
            pred = 1 if (len(class_counts) > 1 and class_counts[1] >= class_counts[0]) else 0
            gpu_votes += pred

        json_pred = 1 if gpu_votes > len(forest_json["trees"]) // 2 else 0

        if sklearn_pred != json_pred:
            mismatches += 1

    match_rate = (n_samples - mismatches) / n_samples * 100
    print(f"\n[Validation] sklearn vs JSON export: {match_rate:.1f}% match "
          f"({n_samples - mismatches}/{n_samples} samples)")
    if mismatches > 0:
        print(f"  WARNING: {mismatches} mismatches (may be due to tie-breaking differences)")
    return mismatches == 0


if __name__ == "__main__":
    export_forest_to_json()
    generate_cpp_header()
    validate_export()
